import { randomBytes } from 'node:crypto';
import { access, readFile, writeFile } from 'node:fs/promises';
import { constants } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const workerDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const varsPath = path.join(workerDir, '.dev.vars');
const marker = '# Generated by setup:local; contains local-only values.';

let contents = '';
try {
	await access(varsPath, constants.F_OK);
	contents = await readFile(varsPath, 'utf8');
} catch (error) {
	if (error.code !== 'ENOENT') {
		throw error;
	}
}

if (contents && !contents.startsWith(`${marker}\n`)) {
	throw new Error('Refusing to use an existing unmarked .dev.vars file. Review or move it, then rerun setup:local.');
}

const variableLines = contents
	.split(/\r?\n/)
	.map(line => line.trim())
	.filter(line => line && !line.startsWith('#'));
if (variableLines.some(line => !/^jwt_secret\s*=/.test(line))) {
	throw new Error('Only the generated local jwt_secret is allowed in .dev.vars; remove additional values before starting.');
}

if (variableLines.some(line => /^jwt_secret\s*=/.test(line))) {
	console.log('Local Worker secret is already configured in mail-worker/.dev.vars.');
	process.exit(0);
}

const line = `jwt_secret=${randomBytes(32).toString('hex')}`;
const updated = contents ? `${contents.trimEnd()}\n${line}\n` : `${marker}\n${line}\n`;
await writeFile(varsPath, updated, { mode: 0o600 });
console.log('Generated a private local Worker secret in ignored mail-worker/.dev.vars.');
